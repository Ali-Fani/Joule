    public static string Translate(string english)
    {
        if (Exact.TryGetValue(english, out string? translated)) return translated;

        var match = MinutesAgo().Match(english);
        if (match.Success) return $"{match.Groups[1].Value} мин назад";
        match = HoursAgo().Match(english);
        if (match.Success) return $"{match.Groups[1].Value} ч назад";
        match = DaysAgo().Match(english);
        if (match.Success) return $"{match.Groups[1].Value} дн. назад";
        match = LastReading().Match(english);
        if (match.Success) return $"Последнее чтение в {match.Groups[1].Value}";
        match = Below().Match(english);
        if (match.Success) return $"ниже {match.Groups[1].Value}%";
        match = NoDataDetail().Match(english);
        if (match.Success) return $"Сейчас нет данных: {Translate(match.Groups[1].Value)}";
        match = ErrorDetail().Match(english);
        if (match.Success) return $"Ошибка чтения: {Translate(match.Groups[1].Value)}";

        return english;
    }

    [GeneratedRegex(@"^(\d+) min ago$")]
