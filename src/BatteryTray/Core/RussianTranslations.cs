    [GeneratedRegex(@"^(\d+) h ago$")]
    private static partial Regex HoursAgo();
    [GeneratedRegex(@"^(\d+) d ago$")]
    private static partial Regex DaysAgo();
    [GeneratedRegex(@"^Last reading at (.+)$")]
    private static partial Regex LastReading();
    [GeneratedRegex(@"^below (\d+)%$", RegexOptions.IgnoreCase)]
    private static partial Regex Below();
    [GeneratedRegex(@"^no data right now: (.+)$", RegexOptions.IgnoreCase)]
    private static partial Regex NoDataDetail();
    [GeneratedRegex(@"^error reading: (.+)$", RegexOptions.IgnoreCase)]
    private static partial Regex ErrorDetail();
